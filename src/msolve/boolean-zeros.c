/* Boolean ring over GF(2): Groebner bases via the common zeros of the
 * input polynomials (option --boolean-zeros).
 *
 * The boolean ring GF(2)[x1, ..., xn]/(x1^2 + x1, ..., xn^2 + xn) is the
 * ring of all functions GF(2)^n -> GF(2), so the ideal generated by the
 * input polynomials consists of all polynomials vanishing on their common
 * zeros P. Its reduced Groebner basis is computed from P by the
 * Buchberger-Moeller algorithm: the squarefree monomials t are handled in
 * increasing order, if the values of t on P are linearly independent of
 * those of the smaller standard monomials, t is a standard monomial,
 * otherwise t is the leading monomial of the basis element t + NF(t),
 * NF(t) being the sum of the standard monomials with the same values on P.
 *
 * P is found by evaluating the input polynomials at all 2^n points, thus
 * this is meant for few variables, e.g. for a single generator describing
 * a set of points. Monomials and points are bit masks, bit k standing for
 * the (k+1)-st variable. The monomial orders are DRL and LEX, both with
 * x1 > x2 > ... > xn. */

/* at most 2^32 points are evaluated */
#define BOOLEAN_ZEROS_MAX_NVARS 32

/* number of monomials whose values are reduced together, each row of
 * the echelon form is read once per batch */
#ifndef BZ_BATCH
#define BZ_BATCH    256
#endif

/* values of the hash map of monomials */
#define BZ_EMPTY    INT32_MIN
#define BZ_QUEUED   -1
#define BZ_NONSTD   -2

/* the zeta transform is done in passes over tiles: the first pass
 * handles the levels inside the words and the first BZ_TILE levels of the
 * word index on contiguous tiles of 2^BZ_TILE words, each further pass
 * the next BZ_TILE2 - BZ_CHUNK levels on tiles of 2^BZ_TILE2 words made of
 * chunks of 2^BZ_CHUNK contiguous words. Since the chunks lie at
 * distances of a power of two they are copied to a buffer, otherwise they
 * evict each other from the cache. */
#define BZ_TILE   15
#define BZ_TILE2  16
#define BZ_CHUNK  5

/* zeta transform of the levels of the row index of nr rows of cl
 * contiguous words each */
static inline void bz_zeta_rows(
    uint64_t *b,
    const uint64_t nr,
    const uint64_t cl
    )
{
  uint64_t h = 1, j, l;

  if (cl == 1 && nr >= 8) {
    /* the first three levels on groups of eight words */
    for (j = 0; j < nr; j += 8) {
      uint64_t *w = b + j;
      w[1] ^= w[0];
      w[3] ^= w[2];
      w[5] ^= w[4];
      w[7] ^= w[6];
      w[2] ^= w[0];
      w[3] ^= w[1];
      w[6] ^= w[4];
      w[7] ^= w[5];
      w[4] ^= w[0];
      w[5] ^= w[1];
      w[6] ^= w[2];
      w[7] ^= w[3];
    }
    h = 8;
  }
  for (; h < nr; h *= 2) {
    const uint64_t hl = h * cl;
    for (j = 0; j < nr; j += 2 * h) {
      uint64_t *restrict r        = b + (j + h) * cl;
      const uint64_t *restrict q  = b + j * cl;
      for (l = 0; l < hl; ++l) {
        r[l] ^= q[l];
      }
    }
  }
}

/* zeta transform of c of 2^nwb words for the levels k0, ..., k1-1 of the
 * word index, and also for the levels inside the words if k0 == 0: word i
 * becomes the sum of the words j with j & ~i == 0 and i & ~j having only
 * bits in these levels. If z is not NULL this is the last pass, then the
 * points where c is not zero are removed from z and c is cleared. */
static void bz_zeta_pass(
    uint64_t *c,
    uint64_t *z,
    const int32_t nwb,
    const int32_t k0,
    const int32_t k1,
    const int32_t nthrds
    )
{
  static const uint64_t lo[6] = {
    0x5555555555555555, 0x3333333333333333, 0x0F0F0F0F0F0F0F0F,
    0x00FF00FF00FF00FF, 0x0000FFFF0000FFFF, 0x00000000FFFFFFFF
  };
  /* a tile consists of 2^(k1-k0) rows of 2^cs contiguous words, row j
   * starts at o + j * 2^k0 */
  const int32_t cs  = k0 < BZ_CHUNK ? k0 : BZ_CHUNK;
  const uint64_t cl = (uint64_t)1 << cs;
  const uint64_t nr = (uint64_t)1 << (k1 - k0);
  const uint64_t nt = (uint64_t)1 << (nwb - (k1 - k0) - cs);
  const int64_t lm  = ((int64_t)1 << (k0 - cs)) - 1;

#pragma omp parallel num_threads(nthrds) if (nt > 1 && nwb > 16)
  {
    uint64_t *buf = k0 > 0 ? (uint64_t *)malloc(nr * cl * sizeof(uint64_t))
      : NULL;
#pragma omp for
    for (int64_t t = 0; t < (int64_t)nt; ++t) {
      const uint64_t o  = (((uint64_t)t & lm) << cs)
        | (((uint64_t)t >> (k0 - cs)) << k1);
      uint64_t j, l;
      uint64_t *b = c + o;
      if (k0 == 0) {
        for (j = 0; j < nr; ++j) {
          uint64_t w  = b[j];
          w ^= (w & lo[0]) << 1;
          w ^= (w & lo[1]) << 2;
          w ^= (w & lo[2]) << 4;
          w ^= (w & lo[3]) << 8;
          w ^= (w & lo[4]) << 16;
          w ^= (w & lo[5]) << 32;
          b[j]  = w;
        }
      } else {
        for (j = 0; j < nr; ++j) {
          memcpy(buf + j * cl, b + (j << k0), cl * sizeof(uint64_t));
        }
        b = buf;
      }
      bz_zeta_rows(b, nr, cl);
      if (z != NULL) {
        for (j = 0; j < nr; ++j) {
          const uint64_t *restrict r  = b + j * cl;
          uint64_t *restrict y        = z + o + (j << k0);
          for (l = 0; l < cl; ++l) {
            y[l] &= ~r[l];
          }
          memset(c + o + (j << k0), 0, cl * sizeof(uint64_t));
        }
      } else if (k0 > 0) {
        for (j = 0; j < nr; ++j) {
          memcpy(c + o + (j << k0), b + j * cl, cl * sizeof(uint64_t));
        }
      }
    }
    free(buf);
  }
}

/* returns the bit array of the common zeros of the input polynomials,
 * bit S is set iff the point with the variables of S equal to 1 is a
 * common zero, NULL if there is not enough memory */
static uint64_t *boolean_common_zeros(
    const data_gens_ff_t *gens,
    const int32_t nthrds
    )
{
  static const uint64_t lo[6] = {
    0x5555555555555555, 0x3333333333333333, 0x0F0F0F0F0F0F0F0F,
    0x00FF00FF00FF00FF, 0x0000FFFF0000FFFF, 0x00000000FFFFFFFF
  };
  const int32_t nv  = gens->nvars;
  const uint64_t np = (uint64_t)1 << nv;
  const uint64_t nw = np < 64 ? 1 : np / 64;
  const int32_t nwb = nv < 6 ? 0 : nv - 6;
  int64_t pos = 0;
  int64_t i;
  int32_t g, j, k;

  uint64_t *z = (uint64_t *)malloc(nw * sizeof(uint64_t));
  uint64_t *c = (uint64_t *)malloc(nw * sizeof(uint64_t));
  /* c is cleared by the last pass of the transform */
  if (z == NULL || c == NULL) {
    free(z);
    free(c);
    return NULL;
  }
#pragma omp parallel for num_threads(nthrds) if (nwb > 16)
  for (i = 0; i < (int64_t)nw; ++i) {
    z[i] = ~(uint64_t)0;
    c[i] = 0;
  }
  if (np < 64) {
    z[0] = ((uint64_t)1 << np) - 1;
  }
  for (g = 0; g < gens->ngens; ++g) {
    for (j = 0; j < gens->lens[g]; ++j, ++pos) {
      const int32_t *e  = gens->exps + pos * nv;
      uint64_t s        = 0;
      for (k = 0; k < nv; ++k) {
        if (e[k] != 0) {
          s |= (uint64_t)1 << k;
        }
      }
      c[s >> 6] ^= (uint64_t)1 << (s & 63);
    }
    /* the value at the point S is the sum of the coefficients of the
     * monomials dividing S */
    if (nv < 6) {
      for (k = 0; k < nv; ++k) {
        c[0] ^= (c[0] & lo[k]) << (1 << k);
      }
      z[0] &= ~c[0];
      c[0]  = 0;
    } else {
      k = nwb < BZ_TILE ? nwb : BZ_TILE;
      bz_zeta_pass(c, k < nwb ? NULL : z, nwb, 0, k, nthrds);
      while (k < nwb) {
        const int32_t k1  = k + BZ_TILE2 - BZ_CHUNK < nwb
          ? k + BZ_TILE2 - BZ_CHUNK : nwb;
        bz_zeta_pass(c, k1 < nwb ? NULL : z, nwb, k, k1, nthrds);
        k = k1;
      }
    }
  }
  free(c);
  return z;
}

/* compares the squarefree monomials a and b w.r.t. DRL or LEX (lex != 0),
 * returns a negative number iff a < b */
static inline int boolean_zeros_cmp(
    const uint32_t a,
    const uint32_t b,
    const int lex
    )
{
  if (a == b) {
    return 0;
  }
  const uint32_t d  = a ^ b;
  if (lex) {
    /* the first differing variable decides */
    return (a >> __builtin_ctz(d)) & 1 ? 1 : -1;
  }
  const int da  = __builtin_popcount(a);
  const int db  = __builtin_popcount(b);
  if (da != db) {
    return da < db ? -1 : 1;
  }
  /* the last differing variable decides */
  return (a >> (31 - __builtin_clz(d))) & 1 ? -1 : 1;
}

/* binary heap of monomials, the smallest one first */
typedef struct {
  uint32_t *m;
  uint64_t ld;
  uint64_t sz;
} bz_heap_t;

static void bz_heap_push(bz_heap_t *h, const uint32_t t, const int lex)
{
  if (h->ld == h->sz) {
    h->sz = 2 * h->sz;
    h->m  = (uint32_t *)realloc(h->m, h->sz * sizeof(uint32_t));
  }
  uint64_t i  = h->ld++;
  while (i > 0 && boolean_zeros_cmp(t, h->m[(i-1)/2], lex) < 0) {
    h->m[i] = h->m[(i-1)/2];
    i       = (i-1)/2;
  }
  h->m[i] = t;
}

static uint32_t bz_heap_pop(bz_heap_t *h, const int lex)
{
  const uint32_t r  = h->m[0];
  const uint32_t t  = h->m[--h->ld];
  uint64_t i  = 0;
  while (2*i+1 < h->ld) {
    uint64_t c  = 2*i+1;
    if (c+1 < h->ld && boolean_zeros_cmp(h->m[c+1], h->m[c], lex) < 0) {
      c++;
    }
    if (boolean_zeros_cmp(h->m[c], t, lex) >= 0) {
      break;
    }
    h->m[i] = h->m[c];
    i       = c;
  }
  h->m[i] = t;
  return r;
}

/* hash map of the monomials met so far, the value is the index of a
 * standard monomial, BZ_QUEUED or BZ_NONSTD */
typedef struct {
  uint32_t key;
  int32_t val;
} bz_entry_t;

typedef struct {
  bz_entry_t *e;
  uint64_t ld;
  uint64_t sz;  /* a power of two */
  int32_t sh;   /* 64 - log2(sz) */
} bz_map_t;

static inline uint64_t bz_map_slot(const bz_map_t *mp, const uint32_t t)
{
  /* Fibonacci hashing, the top bits of the product are the best mixed */
  uint64_t k  = ((uint64_t)t * 0x9E3779B97F4A7C15ULL) >> mp->sh;
  while (mp->e[k].val != BZ_EMPTY && mp->e[k].key != t) {
    k = (k+1) & (mp->sz - 1);
  }
  return k;
}

static inline int32_t bz_map_get(const bz_map_t *mp, const uint32_t t)
{
  return mp->e[bz_map_slot(mp, t)].val;
}

static void bz_map_init(bz_map_t *mp, const int32_t lg)
{
  mp->sz  = (uint64_t)1 << lg;
  mp->sh  = 64 - lg;
  mp->ld  = 0;
  mp->e   = (bz_entry_t *)malloc(mp->sz * sizeof(bz_entry_t));
  for (uint64_t i = 0; i < mp->sz; ++i) {
    mp->e[i].val  = BZ_EMPTY;
  }
}

static void bz_map_set(bz_map_t *mp, const uint32_t t, const int32_t v)
{
  uint64_t k  = bz_map_slot(mp, t);
  if (mp->e[k].val == BZ_EMPTY) {
    if (2 * (mp->ld + 1) > mp->sz) {
      bz_map_t nm;
      bz_map_init(&nm, 64 - mp->sh + 1);
      for (uint64_t i = 0; i < mp->sz; ++i) {
        if (mp->e[i].val != BZ_EMPTY) {
          nm.e[bz_map_slot(&nm, mp->e[i].key)] = mp->e[i];
        }
      }
      nm.ld = mp->ld;
      free(mp->e);
      *mp = nm;
      k = bz_map_slot(mp, t);
    }
    mp->e[k].key  = t;
    mp->ld++;
  }
  mp->e[k].val  = v;
}

/* reduces v by the rows r0, ..., r1-1 in this order, the first mw words
 * of v are values on the points, the others the sum of the standard
 * monomials giving these values, see boolean_zeros_gb() */
static inline void bz_reduce(
    uint64_t *v,
    const uint64_t *red,
    const uint32_t *piv,
    const uint64_t mw,
    const uint64_t r0,
    const uint64_t r1
    )
{
  uint64_t *c = v + mw;
  uint64_t i, r;

  for (r = r0; r < r1; ++r) {
    const uint32_t p  = piv[r];
    if ((v[p / 64] >> (p % 64)) & 1) {
      const uint64_t *row = red + 2 * r * mw;
      for (i = p / 64; i < mw; ++i) {
        v[i] ^= row[i];
      }
      const uint64_t cw = r / 64 + 1;
      for (i = 0; i < cw; ++i) {
        c[i] ^= row[mw + i];
      }
    }
  }
}

/* writes the monomial t to s as msolve prints terms, with coefficient 1
 * if cf != 0, returns the end of the string */
static char *boolean_zeros_monomial_str(
    char *s,
    const uint32_t t,
    const int32_t nv,
    char **vnames,
    const int cf
    )
{
  int32_t k;
  int first = 1;

  if (cf) {
    s += sprintf(s, "1");
    first = 0;
  }
  for (k = 0; k < nv; ++k) {
    if ((t >> k) & 1) {
      s += sprintf(s, first ? "%s^1" : "*%s^1", vnames[k]);
      first = 0;
    }
  }
  if (first) {
    s += sprintf(s, "1");
  }
  return s;
}

static void boolean_zeros_print(
    FILE *file,
    const data_gens_ff_t *gens,
    const int lex,
    const int32_t print_gb,
    const uint64_t ng,
    const uint32_t *lts,
    const uint64_t *nfs,
    const uint64_t *nfo,
    const uint64_t nst,
    const uint32_t *std
    )
{
  const int32_t nv  = gens->nvars;
  const int lead    = print_gb == 1;
  uint64_t i, j;
  int32_t k;

  fprintf(file, lead ? "#Leading ideal data\n" : "#Reduced Groebner basis data\n");
  fprintf(file, "#---\n");
  fprintf(file, "#field characteristic: %" PRIu64 "\n", (uint64_t)gens->field_char);
  fprintf(file, "#boolean ring:         x^2 = x for all variables x\n");
  fprintf(file, "#variable order:       ");
  for (k = 0; k < nv-1; ++k) {
    fprintf(file, "%s, ", gens->vnames[k]);
  }
  fprintf(file, "%s\n", gens->vnames[nv-1]);
  fprintf(file, lex ? "#monomial order:       lexicographical\n"
      : "#monomial order:       graded reverse lexicographical\n");
  if (ng == 1) {
    fprintf(file, "#length of basis:      1 element\n");
  } else {
    fprintf(file, "#length of basis:      %" PRIu64 " elements sorted by increasing leading monomials\n", ng);
  }
  fprintf(file, "#---\n");

  /* the terms of the standard monomials are printed once */
  size_t vl = 0;
  for (k = 0; k < nv; ++k) {
    vl  +=  strlen(gens->vnames[k]) + 3;
  }
  const size_t ml = vl + 4;
  char *buf = (char *)malloc(ml);
  char *sst = lead ? NULL : (char *)malloc(nst * ml);
  if (!lead) {
    for (j = 0; j < nst; ++j) {
      sst[j * ml] = '+';
      boolean_zeros_monomial_str(sst + j * ml + 1, std[j], nv,
          gens->vnames, 1);
    }
  }
  fprintf(file, "[");
  for (i = 0; i < ng; ++i) {
    boolean_zeros_monomial_str(buf, lts[i], nv, gens->vnames, !lead);
    fputs(buf, file);
    if (!lead) {
      /* the standard monomials are indexed in increasing order */
      const uint64_t *nf  = nfs + nfo[i];
      for (j = nfo[i+1] - nfo[i]; j > 0; --j) {
        uint64_t w  = nf[j-1];
        while (w != 0) {
          const int b = 63 - __builtin_clzll(w);
          fputs(sst + ((j-1) * 64 + b) * ml, file);
          w ^= (uint64_t)1 << b;
        }
      }
    }
    fprintf(file, i < ng-1 ? ",\n" : "]:\n");
  }
  free(sst);
  free(buf);
}

/* computes the reduced Groebner basis of the ideal generated by the
 * input polynomials in the boolean ring w.r.t. DRL or LEX (lex != 0) via
 * their common zeros and prints it to fn (stdout if fn is NULL) as
 * print_gb states; the input polynomials have to be squarefree, see
 * make_input_boolean(). Returns 0 on success, -1 otherwise. */
static int boolean_zeros_gb(
    const data_gens_ff_t *gens,
    const char *fn,
    const int lex,
    const int32_t print_gb,
    const int32_t nthrds,
    const int32_t info_level
    )
{
  const int32_t nv  = gens->nvars;
  uint64_t i, j;
  int32_t k;

  if (nv > BOOLEAN_ZEROS_MAX_NVARS) {
    fprintf(ERRSTREAM, "The computation via the common zeros (option ");
    fprintf(ERRSTREAM, "--boolean-zeros) supports at most %d variables.\n",
        BOOLEAN_ZEROS_MAX_NVARS);
    return -1;
  }
  double rt0  = realtime();
  if (info_level > 0) {
    fprintf(VERBSTREAM, "\n--------------- INPUT DATA ---------------\n");
    fprintf(VERBSTREAM, "#variables              %11d\n", nv);
    fprintf(VERBSTREAM, "#equations              %11d\n", gens->ngens);
    fprintf(VERBSTREAM, "field characteristic    %11d\n", 2);
    fprintf(VERBSTREAM, "boolean ring            x^2 = x\n");
    fprintf(VERBSTREAM, "monomial order          %11s\n", lex ? "LEX" : "DRL");
    fprintf(VERBSTREAM, "algorithm               Buchberger-Moeller on the common zeros\n");
    fprintf(VERBSTREAM, "------------------------------------------\n");
  }

  /* the common zeros */
  uint64_t *z = boolean_common_zeros(gens, nthrds);
  if (z == NULL) {
    fprintf(ERRSTREAM, "Not enough memory for evaluating the input ");
    fprintf(ERRSTREAM, "polynomials at all points.\n");
    return -1;
  }
  const uint64_t np = (uint64_t)1 << nv;
  const uint64_t nw = np < 64 ? 1 : np / 64;
  uint64_t m  = 0;
  for (i = 0; i < nw; ++i) {
    m +=  __builtin_popcountll(z[i]);
  }
  uint32_t *pts = (uint32_t *)malloc((m > 0 ? m : 1) * sizeof(uint32_t));
  for (i = 0, j = 0; i < nw; ++i) {
    uint64_t w  = z[i];
    while (w != 0) {
      pts[j++]  = (uint32_t)(i * 64 + __builtin_ctzll(w));
      w &= w - 1;
    }
  }
  free(z);
  double rt1  = realtime();
  if (info_level > 0) {
    fprintf(VERBSTREAM, "#common zeros           %11" PRIu64 "   %10.2f sec\n",
        m, rt1 - rt0);
  }

  FILE *ofile = fn != NULL ? fopen(fn, "ab") : stdout;
  if (m == 0) {
    /* no common zeros, the ideal is the whole ring */
    if (print_gb > 0) {
      const uint32_t one  = 0;
      const uint64_t nfo[2] = {0, 0};
      boolean_zeros_print(ofile, gens, lex, print_gb, 1, &one, NULL, nfo,
          0, NULL);
    }
    if (ofile != stdout) {
      fclose(ofile);
    }
    free(pts);
    return 0;
  }

  /* data of the Buchberger-Moeller algorithm: there are exactly m
   * standard monomials, the rows red are in echelon form, the first mw
   * words of row r are the values of the r-th standard monomial on the
   * points reduced by the rows before, the others the standard monomials
   * whose sum gives these values, row r has the pivot piv[r] and no bits
   * before it. The values of the monomials of a batch bt are stored and
   * reduced in the same way in bv. */
  const uint64_t mw   = (m + 63) / 64;
  uint32_t *std       = (uint32_t *)malloc(m * sizeof(uint32_t));
  uint32_t *piv       = (uint32_t *)malloc(m * sizeof(uint32_t));
  uint64_t *red       = (uint64_t *)malloc(2 * m * mw * sizeof(uint64_t));
  uint64_t *xv        = (uint64_t *)calloc((uint64_t)nv * mw, sizeof(uint64_t));
  uint32_t *bt        = (uint32_t *)malloc(BZ_BATCH * sizeof(uint32_t));
  uint64_t *bv        = (uint64_t *)malloc(BZ_BATCH * 2 * mw * sizeof(uint64_t));
  if (std == NULL || piv == NULL || red == NULL || xv == NULL
      || bt == NULL || bv == NULL) {
    fprintf(ERRSTREAM, "Not enough memory for the linear algebra on ");
    fprintf(ERRSTREAM, "%" PRIu64 " common zeros.\n", m);
    free(std);
    free(piv);
    free(red);
    free(xv);
    free(bt);
    free(bv);
    free(pts);
    if (ofile != stdout) {
      fclose(ofile);
    }
    return -1;
  }
  /* the values of the variables */
  for (i = 0; i < m; ++i) {
    for (k = 0; k < nv; ++k) {
      if ((pts[i] >> k) & 1) {
        xv[k * mw + i / 64] |= (uint64_t)1 << (i % 64);
      }
    }
  }
  free(pts);
  /* the basis elements, the leading monomials and the sums of standard
   * monomials, element i uses the words nfo[i], ..., nfo[i+1]-1 of nfs */
  uint64_t ng   = 0;
  uint64_t gsz  = 64;
  uint32_t *lts = (uint32_t *)malloc(gsz * sizeof(uint32_t));
  uint64_t *nfo = (uint64_t *)malloc((gsz + 1) * sizeof(uint64_t));
  uint64_t nsz  = 1024;
  uint64_t *nfs = (uint64_t *)malloc(nsz * sizeof(uint64_t));
  nfo[0]  = 0;

  bz_heap_t heap;
  heap.sz = 1024;
  heap.ld = 0;
  heap.m  = (uint32_t *)malloc(heap.sz * sizeof(uint32_t));
  bz_map_t map;
  bz_map_init(&map, 10);

  /* the rows are reduced in blocks of about 4 MB, so that a block is read
   * from memory only once for all monomials of a batch */
  const uint64_t rb = ((uint64_t)1 << 22) / (16 * mw) > 0
    ? ((uint64_t)1 << 22) / (16 * mw) : 1;
  uint64_t b, nb, nbt = 0, nbr = 0, nst = 0;
  bz_heap_push(&heap, 0, lex);
  bz_map_set(&map, 0, BZ_QUEUED);
  while (heap.ld > 0) {
    /* the next batch: the smallest monomials which are still candidates,
     * all monomials pushed later are bigger than them, thus their
     * divisors are handled or in the batch */
    nb  = 0;
    while (nb < BZ_BATCH && heap.ld > 0) {
      const uint32_t t  = bz_heap_pop(&heap, lex);
      int32_t sd  = 0;
      for (k = 0; k < nv; ++k) {
        if ((t >> k) & 1) {
          sd  = bz_map_get(&map, t ^ ((uint32_t)1 << k));
          if (sd == BZ_NONSTD) {
            break;
          }
        }
      }
      if (sd == BZ_NONSTD) {
        bz_map_set(&map, t, BZ_NONSTD);
        continue;
      }
      bt[nb++]  = t;
    }
    if (nb == 0) {
      break;
    }
    nbt++;
    /* their values on the points, reduced by the rows known so far */
    const uint64_t nr = nst;
#pragma omp parallel num_threads(nthrds) if (nb > 1 && nr * mw > ((uint64_t)1 << 16))
    {
#pragma omp for
      for (b = 0; b < nb; ++b) {
        uint64_t *e = bv + 2 * b * mw;
        uint64_t l;
        for (l = 0; l < mw; ++l) {
          e[l] = ~(uint64_t)0;
        }
        if (m % 64 != 0) {
          e[mw-1] = ((uint64_t)1 << (m % 64)) - 1;
        }
        for (int32_t x = 0; x < nv; ++x) {
          if ((bt[b] >> x) & 1) {
            const uint64_t *vx  = xv + (uint64_t)x * mw;
            for (l = 0; l < mw; ++l) {
              e[l] &= vx[l];
            }
          }
        }
        memset(e + mw, 0, mw * sizeof(uint64_t));
      }
      for (uint64_t r0 = 0; r0 < nr; r0 += rb) {
        const uint64_t r1 = r0 + rb < nr ? r0 + rb : nr;
#pragma omp for schedule(dynamic, 1)
        for (b = 0; b < nb; ++b) {
          bz_reduce(bv + 2 * b * mw, red, piv, mw, r0, r1);
        }
      }
    }
    /* the batch in increasing order, reduced by the new rows */
    int nu      = 0;
    uint32_t um = 0;
    for (b = 0; b < nb; ++b) {
      const uint32_t t  = bt[b];
      if (nu > 0 && boolean_zeros_cmp(um, t, lex) < 0) {
        /* a monomial queued in this batch is smaller than the rest of
         * the batch, so the rest has to wait */
        for (; b < nb; ++b) {
          bz_heap_push(&heap, bt[b], lex);
        }
        nbr++;
        break;
      }
      /* t is a standard monomial or a leading monomial of the reduced
       * Groebner basis iff all t / x are standard monomials */
      int32_t sd  = 0;
      for (k = 0; k < nv; ++k) {
        if ((t >> k) & 1) {
          sd  = bz_map_get(&map, t ^ ((uint32_t)1 << k));
          if (sd < 0) {
            break;
          }
        }
      }
      if (sd < 0) {
        bz_map_set(&map, t, BZ_NONSTD);
        continue;
      }
      uint64_t *e = bv + 2 * b * mw;
      uint64_t *c = e + mw;
      bz_reduce(e, red, piv, mw, nr, nst);
      uint64_t f  = 0;
      while (f < mw && e[f] == 0) {
        f++;
      }
      if (f == mw) {
        /* t is the leading monomial of t + the sum of the standard
         * monomials in c */
        const uint64_t cw = (nst + 63) / 64;
        if (ng == gsz) {
          gsz = 2 * gsz;
          lts = (uint32_t *)realloc(lts, gsz * sizeof(uint32_t));
          nfo = (uint64_t *)realloc(nfo, (gsz + 1) * sizeof(uint64_t));
        }
        while (nfo[ng] + cw > nsz) {
          nsz = 2 * nsz;
          nfs = (uint64_t *)realloc(nfs, nsz * sizeof(uint64_t));
        }
        lts[ng] = t;
        memcpy(nfs + nfo[ng], c, cw * sizeof(uint64_t));
        nfo[ng+1] = nfo[ng] + cw;
        ng++;
        bz_map_set(&map, t, BZ_NONSTD);
        continue;
      }
      /* t is a new standard monomial */
      uint64_t *row = red + 2 * nst * mw;
      memcpy(row, e, 2 * mw * sizeof(uint64_t));
      row[mw + nst / 64] ^= (uint64_t)1 << (nst % 64);
      piv[nst]  = (uint32_t)(f * 64 + __builtin_ctzll(e[f]));
      std[nst]  = t;
      bz_map_set(&map, t, (int32_t)nst);
      nst++;
      for (k = 0; k < nv; ++k) {
        const uint32_t u  = t | ((uint32_t)1 << k);
        if (u != t && bz_map_get(&map, u) == BZ_EMPTY) {
          bz_map_set(&map, u, BZ_QUEUED);
          bz_heap_push(&heap, u, lex);
          if (nu == 0 || boolean_zeros_cmp(u, um, lex) < 0) {
            um  = u;
            nu  = 1;
          }
        }
      }
    }
  }
  double rt2  = realtime();
  if (info_level > 0) {
    fprintf(VERBSTREAM, "#standard monomials     %11" PRIu64 "\n", nst);
    if (info_level > 1) {
      fprintf(VERBSTREAM, "#batches                %11" PRIu64 "\n", nbt);
      fprintf(VERBSTREAM, "#interrupted batches    %11" PRIu64 "\n", nbr);
    }
    fprintf(VERBSTREAM, "#basis elements         %11" PRIu64 "   %10.2f sec\n",
        ng, rt2 - rt1);
  }
  if (print_gb > 0) {
    boolean_zeros_print(ofile, gens, lex, print_gb, ng, lts, nfs, nfo,
        nst, std);
  }
  if (ofile != stdout) {
    fclose(ofile);
  }
  double rt3  = realtime();
  if (info_level > 0) {
    fprintf(VERBSTREAM, "output                                %10.2f sec\n",
        rt3 - rt2);
    fprintf(VERBSTREAM, "overall(elapsed)                      %10.2f sec\n",
        rt3 - rt0);
    fprintf(VERBSTREAM, "------------------------------------------\n");
  }

  free(heap.m);
  free(map.e);
  free(lts);
  free(nfo);
  free(nfs);
  free(std);
  free(piv);
  free(red);
  free(xv);
  free(bt);
  free(bv);
  return 0;
}
